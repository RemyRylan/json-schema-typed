// Generates compile-time compatibility tests from the official
// JSON-Schema-Test-Suite: every `schema` in the suite must satisfy our
// `JSONSchema` type for that draft. This guards against the types rejecting
// spec-valid schemas.
//
// Schemas that use keywords outside the specification (the suite has a few,
// e.g. the "unknown keyword" tests) are skipped, because TypeScript's excess
// property checks reject unknown keys by design.
//
// Usage (requires the submodule): git submodule update --init test/suite/JSON-Schema-Test-Suite
//        npm run test:suite:generate

import * as fs from "node:fs/promises";
import * as path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SUITE_DIR = path.join(HERE, "JSON-Schema-Test-Suite");

/** Suite directory → package export to check it against. */
const DRAFTS: Array<{ suiteDir: string; exportName: string }> = [
  { suiteDir: "draft7", exportName: "draft-07" },
  { suiteDir: "draft2019-09", exportName: "draft-2019-09" },
  { suiteDir: "draft2020-12", exportName: "draft-2020-12" },
  { suiteDir: "v1", exportName: "v1" },
];

/**
 * Keywords the suite uses that are deliberately not in the specification:
 * the "unknown keyword" tests, proposal keywords, and keywords removed from a
 * later dialect but kept in the suite's optional compatibility tests. A schema
 * using one of these is skipped. Any OTHER keyword missing from the module is
 * an error, so a keyword accidentally dropped from a definition cannot make
 * its tests silently disappear.
 */
const NON_SPEC_KEYWORDS: Record<string, ReadonlySet<string>> = {
  "draft-07": new Set(["unknown-keyword", "unknown/keyword", "array_of_schemas"]),
  "draft-2019-09": new Set(["unknown-keyword", "unknown/keyword", "array_of_schemas"]),
  "draft-2020-12": new Set(["unknown-keyword", "unknown/keyword", "array_of_schemas"]),
  v1: new Set([
    "unknown-keyword", "unknown/keyword", "array_of_schemas",
    "propertyDependencies", // proposal
    "dependencies", // removed in v1; optional/dependencies-compatibility.json
  ]),
};

/** Keywords whose value is a schema (or, for `items`, a schema or array). */
const SCHEMA_KEYS = new Set([
  "additionalItems", "additionalProperties", "contains", "contentSchema",
  "else", "if", "items", "not", "propertyNames", "then", "unevaluatedItems",
  "unevaluatedProperties",
]);
/** Keywords whose value is an array of schemas. */
const SCHEMA_ARRAY_KEYS = new Set(["allOf", "anyOf", "oneOf", "prefixItems"]);
/** Keywords whose value is a map of arbitrary names to schemas. */
const SCHEMA_MAP_KEYS = new Set([
  "$defs", "definitions", "dependentSchemas", "patternProperties", "properties",
  "dependencies", // values are schemas or string arrays
]);

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };

const isObject = (v: Json): v is { [key: string]: Json } =>
  typeof v === "object" && v !== null && !Array.isArray(v);

/** Returns the first non-spec keyword found anywhere in the schema, if any. */
const findUnknownKeyword = (
  schema: Json,
  keywords: ReadonlySet<string>,
): string | undefined => {
  if (!isObject(schema)) return undefined;
  for (const [key, value] of Object.entries(schema)) {
    if (!keywords.has(key)) return key;
    let nested: Json[] = [];
    if (SCHEMA_KEYS.has(key)) {
      nested = Array.isArray(value) ? value : [value];
    } else if (SCHEMA_ARRAY_KEYS.has(key) && Array.isArray(value)) {
      nested = value;
    } else if (SCHEMA_MAP_KEYS.has(key) && isObject(value)) {
      nested = Object.values(value).filter((v) => !Array.isArray(v));
    }
    for (const n of nested) {
      const unknown = findUnknownKeyword(n, keywords);
      if (unknown !== undefined) return unknown;
    }
  }
  return undefined;
};

const walk = async (dir: string): Promise<string[]> => {
  const out: string[] = [];
  for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...await walk(full));
    else if (entry.name.endsWith(".json")) out.push(full);
  }
  return out.sort();
};

const suiteCommit = execFileSync("git", ["rev-parse", "--short", "HEAD"], {
  cwd: SUITE_DIR,
  encoding: "utf8",
}).trim();

for (const { suiteDir, exportName } of DRAFTS) {
  const mod = await import(`json-schema-typed/${exportName}`).catch(() => null);
  if (mod === null) {
    console.log(`${exportName}: module not built, skipping`);
    continue;
  }
  const keywords = new Set<string>(mod.keywords);
  const testsDir = path.join(SUITE_DIR, "tests", suiteDir);

  const lines: string[] = [
    "// @generated by test/suite/generate.ts — do not edit.",
    `// Source: json-schema-org/JSON-Schema-Test-Suite@${suiteCommit}, tests/${suiteDir}`,
    "//",
    "// Every schema in the official test suite must satisfy our JSONSchema type.",
    "// Checked by `npm run test:types`.",
    "",
    `import type { JSONSchema } from "json-schema-typed/${exportName}";`,
    "",
  ];

  let included = 0;
  const skipped: string[] = [];

  for (const file of await walk(testsDir)) {
    const rel = path.relative(testsDir, file).split(path.sep).join("/");
    const groups = JSON.parse(await fs.readFile(file, "utf8")) as Array<
      { description: string; schema: Json }
    >;
    for (const group of groups) {
      const unknown = findUnknownKeyword(group.schema, keywords);
      if (unknown !== undefined) {
        if (!NON_SPEC_KEYWORDS[exportName].has(unknown)) {
          throw new Error(
            `${exportName}: ${rel} "${group.description}" uses \`${unknown}\`, ` +
              "which is neither a keyword of the module nor a known non-spec keyword",
          );
        }
        skipped.push(`${rel}: "${group.description}" (non-spec keyword \`${unknown}\`)`);
        continue;
      }
      const source = JSON.stringify(group.schema, undefined, 2);
      lines.push(
        `// ${rel}: ${group.description}`,
        `(${source}) satisfies JSONSchema;`,
        "",
      );
      included++;
    }
  }

  if (skipped.length > 0) {
    lines.push(
      "// Skipped:",
      ...skipped.map((s) => `//   ${s}`),
      "",
    );
  }

  const outFile = path.join(HERE, `${exportName.replaceAll("-", "_")}.test.ts`);
  await fs.writeFile(outFile, lines.join("\n"));
  console.log(`${exportName}: ${included} schemas (${skipped.length} skipped) → ${path.relative(process.cwd(), outFile)}`);
}
